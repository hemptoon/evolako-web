#!/usr/bin/env python3
"""Evolako social banners (YouTube 2048x1152, X 1500x500) in the layout of the current ones, with
"Radimo u celoj Srbiji" instead of "Beograd · Novi Sad · Vojvodina" (decision 27.10.2026).
Drawn from the site's own files (Onest woff2 + logo SVG from site/dist), nothing generated by a model.
    python3 site/build.py && python3 brand/social/make_banners.py [--original]
--original also renders the old city line (orig-*.png), to compare the layout with the banners that were live until
28.10.2026. Needs Playwright with Chromium. The PNGs here are the YouTube banner and the X header of 28.10.2026.
"""
import os, socket, subprocess, sys, time

DIST = os.environ.get('EVO_DIST') or os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'site', 'dist')
OUT = os.path.dirname(os.path.abspath(__file__))
A = '/_a/cdn.prod.website-files.com/6ab19bf9a3bb86f8fb7bba00/'
LOGO = A + '6abb0e4201016e0e33e4f62c_evolako-logo-tamna-pozadina.svg'
CSS = '/_a/fonts.googleapis.com/' + [f for f in os.listdir(os.path.join(DIST, '_a', 'fonts.googleapis.com')) if f.endswith('.css')][0]

BASE_CSS = """
html,body{margin:0;overflow:hidden}
body{position:relative;font-family:Onest,sans-serif;-webkit-font-smoothing:antialiased;background:#0B1220}
.a{color:#F5F7FB}.b{color:#6290FF}
.dot{display:inline-block;border-radius:50%;background:#2E6BFF;box-shadow:0 0 12px 3px rgba(46,107,255,.55)}
"""

YT = """<!doctype html><html><head><meta charset="utf-8"><link rel="stylesheet" href="{base}{css}"><style>{basecss}
html,body{{width:2048px;height:1152px}}
body{{background:radial-gradient(ellipse 900px 640px at 20% 100%,rgba(46,107,255,.34),rgba(46,107,255,.10) 50%,rgba(11,18,32,0) 78%),#0B1220}}
.box{{position:absolute;left:467px;top:436px;width:1116px}}
.logo{{display:block;width:166px}}
.url{{position:absolute;right:0;top:6px;font-size:21px;font-weight:500;color:#8B94A8}}
h1{{margin:34px 0 0;font-weight:800;font-size:56px;line-height:1.1;letter-spacing:-0.015em;white-space:nowrap}}
.sub{{margin-top:22px;font-size:23px;font-weight:400;color:#C3CADB}}
.foot{{margin-top:52px;display:flex;align-items:center;gap:12px;font-size:16px;font-weight:600;color:#8B94A8;letter-spacing:.04em}}
.dot{{width:11px;height:11px}}
</style></head><body><div class="box">
<img class="logo" src="{base}{logo}" alt=""><div class="url">evolako.rs</div>
<h1><span class="a">Puni auto tamo gde parkiraš.</span> <span class="b">Dok spavaš.</span></h1>
<div class="sub">Kućno punjenje EV — punjač, MID brojilo i aplikacija</div>
<div class="foot"><span class="dot"></span><span>{foot}</span></div>
</div></body></html>"""

X = """<!doctype html><html><head><meta charset="utf-8"><link rel="stylesheet" href="{base}{css}"><style>{basecss}
html,body{{width:1500px;height:500px}}
body{{background:radial-gradient(ellipse 720px 470px at 15% 110%,rgba(46,107,255,.34),rgba(46,107,255,.10) 50%,rgba(11,18,32,0) 78%),#0B1220}}
.box{{position:absolute;right:90px;top:104px;text-align:right}}
.logo{{display:inline-block;width:191px}}
h1{{margin:28px 0 0;font-weight:800;font-size:56px;line-height:1.1;letter-spacing:-0.015em}}
h1 span{{display:block}}
.sub{{margin-top:24px;font-size:23.8px;font-weight:400;color:#C3CADB}}
.foot{{margin-top:24px;font-size:17.3px;font-weight:600;color:#8B94A8;letter-spacing:.04em}}
</style></head><body><div class="box">
<img class="logo" src="{base}{logo}" alt="">
<h1><span class="a">Puni auto tamo gde parkiraš.</span><span class="b">Dok spavaš.</span></h1>
<div class="sub">Kućno punjenje EV — punjač, MID brojilo i aplikacija</div>
<div class="foot">{foot}</div>
</div></body></html>"""

JOBS = [
    ('evolako-youtube-banner-2048x1152.png', YT, (2048, 1152), 'RADIMO U CELOJ SRBIJI'),
    ('evolako-x-header-1500x500.png', X, (1500, 500), 'RADIMO U CELOJ SRBIJI · EVOLAKO.RS'),
]
ORIG = [
    ('orig-youtube.png', YT, (2048, 1152), 'BEOGRAD · NOVI SAD · VOJVODINA'),
    ('orig-x.png', X, (1500, 500), 'BEOGRAD · NOVI SAD · VOJVODINA · EVOLAKO.RS'),
]


def main():
    s = socket.socket(); s.bind(('127.0.0.1', 0)); port = s.getsockname()[1]; s.close()
    srv = subprocess.Popen([sys.executable, '-m', 'http.server', str(port), '--bind', '127.0.0.1', '--directory', DIST],
                           stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    time.sleep(1)
    base = 'http://127.0.0.1:%d' % port
    from playwright.sync_api import sync_playwright
    jobs = JOBS + (ORIG if '--original' in sys.argv else [])
    try:
        with sync_playwright() as pw:
            b = pw.chromium.launch()
            for name, tpl, (w, h), foot in jobs:
                page = b.new_page(viewport={'width': w, 'height': h}, device_scale_factor=1)
                page.goto(base + '/robots.txt')
                page.set_content(tpl.format(base=base, css=CSS, logo=LOGO, foot=foot, basecss=BASE_CSS), wait_until='networkidle')
                page.evaluate('document.fonts.ready')
                fam = page.evaluate("getComputedStyle(document.querySelector('h1')).fontFamily")
                ok = page.evaluate("document.fonts.check('800 54px Onest')")
                r = page.evaluate("(() => { const q = s => { const e = document.querySelector(s); if (!e) return null; const b = e.getBoundingClientRect(); return [Math.round(b.left), Math.round(b.top), Math.round(b.right), Math.round(b.bottom)]; }; return {box: q('.box'), h1: q('h1 span:last-child'), sub: q('.sub'), foot: q('.foot'), logo: q('.logo')}; })()")
                page.wait_for_timeout(300)
                p = os.path.join(OUT, name)
                page.screenshot(path=p)
                print(name, fam, 'font ok' if ok else 'FONT MISSING', r)
                page.close()
            b.close()
    finally:
        srv.terminate()


if __name__ == '__main__':
    main()
