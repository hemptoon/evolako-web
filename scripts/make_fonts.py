#!/usr/bin/env python3
"""Onest -> self-hosted WOFF2 subsets (latin, latin-ext, cyrillic) for weights 350..800.

Source: the static Onest TTFs from the iOS repo (SIL OFL 1.1, no Reserved Font Name).
Needs: pip install fonttools brotli.   Run: python3 scripts/make_fonts.py
Writes src/assets/fonts/onest-<weight>-<subset>.woff2, src/styles/fonts.css and public/licenses/OFL.txt.
"""
import os
import shutil
import subprocess
import sys

IOS = os.environ.get("IOS_SRC", "/home/claude/src/ios")
SRC = os.path.join(IOS, "EvolakoKit/Sources/DesignSystem/Resources/Fonts")
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src/assets/fonts")
CSS = os.path.join(ROOT, "src/styles/fonts.css")

WEIGHTS = {350: "Onest-Book", 400: "Onest-Regular", 500: "Onest-Medium",
           600: "Onest-SemiBold", 700: "Onest-Bold", 800: "Onest-ExtraBold"}

# Google Fonts ranges, plus the arrows and math signs the product text uses (→ ≈ ≤ ≥ №).
SUBSETS = {
    "latin": "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,"
             "U+2000-206F,U+20AC,U+2122,U+2190-2193,U+2212,U+2215,U+2248,U+2264-2265,U+FEFF,U+FFFD",
    "latin-ext": "U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+1D00-1DBF,U+1E00-1E9F,"
                 "U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF",
    "cyrillic": "U+0301,U+0400-045F,U+0490-0491,U+04B0-04B1,U+2116",
}

def main() -> None:
    if not os.path.isdir(SRC):
        sys.exit(f"Onest TTFs not found in {SRC} (set IOS_SRC)")
    os.makedirs(OUT, exist_ok=True)
    faces = []
    for weight, name in WEIGHTS.items():
        for subset, unicodes in SUBSETS.items():
            target = os.path.join(OUT, f"onest-{weight}-{subset}.woff2")
            subprocess.run([
                sys.executable, "-m", "fontTools.subset", os.path.join(SRC, name + ".ttf"),
                f"--unicodes={unicodes}", "--flavor=woff2", f"--output-file={target}",
                "--layout-features=kern,liga,calt,ccmp,locl,mark,mkmk,tnum,pnum,case",
                "--no-hinting", "--desubroutinize", "--name-IDs=*", "--name-legacy", "--name-languages=*",
            ], check=True)
            faces.append((weight, subset, unicodes))
    lines = ["/* Generated by scripts/make_fonts.py — Onest (SIL OFL 1.1), self-hosted WOFF2 subsets. */"]
    for weight, subset, unicodes in faces:
        ranges = unicodes.replace(",", ", ")
        lines.append(
            "@font-face {\n"
            "  font-family: \"Onest\";\n"
            "  font-style: normal;\n"
            f"  font-weight: {weight};\n"
            "  font-display: swap;\n"
            f"  src: url(\"../assets/fonts/onest-{weight}-{subset}.woff2\") format(\"woff2\");\n"
            f"  unicode-range: {ranges};\n"
            "}"
        )
    with open(CSS, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    lic = os.path.join(ROOT, "public/licenses")
    os.makedirs(lic, exist_ok=True)
    shutil.copyfile(os.path.join(SRC, "OFL.txt"), os.path.join(lic, "OFL.txt"))
    total = sum(os.path.getsize(os.path.join(OUT, n)) for n in os.listdir(OUT))
    print(f"{len(faces)} faces, {total // 1024} KB")

if __name__ == "__main__":
    main()
