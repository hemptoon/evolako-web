// Vendors the subset of Lucide icons the product uses (ISC licence) into src/ui/icon-data.ts.
// Each icon becomes a list of [tag, attributes] so the Icon component builds real SVG nodes (no innerHTML).
// Run: node scripts/make_icons.mjs   (needs the lucide-static dev dependency)
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const lucide = join(root, "node_modules/lucide-static");

// Product name -> Lucide name. One consistent 1.75 px line set.
const ICONS = {
  bolt: "zap", chart: "chart-column", statement: "receipt-text", user: "circle-user-round", bell: "bell",
  moon: "moon", sun: "sun", monitor: "monitor", globe: "globe", check: "check", checkCircle: "circle-check",
  close: "x", chevronRight: "chevron-right", chevronDown: "chevron-down", chevronLeft: "chevron-left",
  external: "arrow-up-right", arrowRight: "arrow-right", copy: "copy", share: "share-2", download: "download",
  printer: "printer", wrench: "wrench", alert: "triangle-alert", wifiOff: "wifi-off", clock: "clock",
  calendar: "calendar", calendarClock: "calendar-clock", pin: "map-pin", home: "house", briefcase: "briefcase",
  car: "car", users: "users", gift: "gift", box: "package", truck: "truck", mail: "mail",
  whatsapp: "message-circle", viber: "message-square", telegram: "send", send: "send", logout: "log-out",
  trash: "trash-2", info: "info", help: "circle-help", lock: "lock", shield: "shield-check", search: "search",
  plus: "plus", minus: "minus", camera: "camera", image: "image", pause: "pause", play: "play",
  refresh: "refresh-cw", settings: "settings", more: "ellipsis", qr: "qr-code", tag: "tag", plug: "plug-zap",
  gauge: "gauge", list: "list", xCircle: "circle-x", pencil: "pencil", fileDown: "file-down", history: "history",
  hourglass: "hourglass", bank: "landmark", ruler: "ruler", circleAlert: "circle-alert", userX: "user-round-x",
  sparkles: "sparkles", link: "link-2", badgeCheck: "badge-check", book: "book-open", sheet: "file-spreadsheet",
  inbox: "inbox", charger: "ev-charger", calendarPlus: "calendar-plus", eye: "eye", languages: "languages",
  playCircle: "circle-play", cable: "cable",
};

const out = [];
for (const [name, file] of Object.entries(ICONS)) {
  const svg = readFileSync(join(lucide, "icons", `${file}.svg`), "utf8");
  const nodes = [];
  for (const m of svg.matchAll(/<(path|circle|rect|line|polyline|polygon|ellipse)\s([^>]*?)\/?>/g)) {
    const attrs = {};
    for (const a of m[2].matchAll(/([a-zA-Z][a-zA-Z0-9-]*)="([^"]*)"/g)) attrs[a[1]] = a[2];
    nodes.push([m[1], attrs]);
  }
  if (!nodes.length) throw new Error(`no shapes in ${file}`);
  out.push(`  ${name}: ${JSON.stringify(nodes)},`);
}

const header = `// Generated by scripts/make_icons.mjs — do not edit.
// Icons: Lucide (https://lucide.dev), ISC License, Copyright (c) Lucide Icons and Contributors /
// Feather (MIT) Copyright (c) 2013-2023 Cole Bemis. Full text: public/licenses/lucide.txt
`;
writeFileSync(join(root, "src/ui/icon-data.ts"),
  `${header}export type IconNode = [string, Record<string, string>];\n\nexport const ICONS = {\n${out.join("\n")}\n} satisfies Record<string, IconNode[]>;\n\nexport type IconName = keyof typeof ICONS;\n`);
mkdirSync(join(root, "public/licenses"), { recursive: true });
copyFileSync(join(lucide, "LICENSE"), join(root, "public/licenses/lucide.txt"));
console.log(`${Object.keys(ICONS).length} icons`);
